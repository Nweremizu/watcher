const require = createRequire(import.meta.url)
const root = dirname(require.resolve('framework7-icons/package.json'))
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const license = readFileSync(join(root, 'LICENSE'), 'utf8').trim()

const compact = (d: string) =>
  d.replace(/-?\d*\.?\d+(?:e-?\d+)?/gi, n => String(+(+n).toFixed(1))).replace(/\s*([A-Za-z])\s*/g, '$1').replace(/\s+/g, ' ').trim()

const has = (name: string) => existsSync(join(root, 'svg', `${name}.svg`))
/** Mirror a path across the 56px grid's vertical centre line. */
function flipX(d: string) {
  const subs = parsePath(d), fx = (p: [number, number]): [number, number] => [56 - p[0], p[1]]
  for (const n of subs.flatMap(s => s.nodes)) { n.x = 56 - n.x; if (n.in) n.in = fx(n.in); if (n.out) n.out = fx(n.out) }
  return serializePath(subs)
}
function load(src: Src) {
  const want = typeof src === 'string' ? src : src.name
  const name = !want.endsWith('_fill') && has(`${want}_fill`) ? `${want}_fill` : want
  const svg = readFileSync(join(root, 'svg', `${name}.svg`), 'utf8')
  if (!/viewBox="0 0 56 56"/.test(svg)) throw new Error(`${name}: expected a 56×56 viewBox`)
  let d = [...svg.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)].map(m => m[1]).join(' ')
  if (!d) throw new Error(`${name}: no path data`)
  if (typeof src !== 'string') d = flipX(d)
  return { name: name + (typeof src === 'string' ? '' : ' (mirrored)'), d: compact(d) }
}

const lines = Object.entries(MAP).map(([key, src]) => { const { name, d } = load(src); return `  ${key}: '${d}', // ${name}` })
const out = `// Generated by scripts/icons.ts from framework7-icons v${version}. Do not edit; run \`npm run icons\`.
/*
${license}
*/
export const ICONS = {
${lines.join('\n')}
} as const
/** Filled glyphs on a 56×56 grid (SF Symbols proportions). */
export const ICON_VIEWBOX = 56
export const ICONS_VERSION = '${version}'
`
writeFileSync(new URL('../src/icons.ts', import.meta.url), out)
console.log(`icons: ${lines.length} from framework7-icons v${version}, ${(out.length / 1024).toFixed(1)} kB`)
